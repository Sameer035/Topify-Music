        // DOM Elements
        const songsContainer = document.getElementById('songs-container');
        const audioPlayer = document.getElementById('audio-player');
        const playBtn = document.getElementById('play-btn');
        const currentSongImage = document.getElementById('current-song-image');
        const currentSongName = document.getElementById('current-song-name');
        const currentSongArtist = document.getElementById('current-song-artist');
        const progressBar = document.querySelector('.progress');
        const currentTimeSpan = document.getElementById('current-time');
        const durationSpan = document.getElementById('duration');
        const volumeBtn = document.getElementById('volume-btn');
        const volumeSlider = document.getElementById('volume-slider');
        const volumeProgress = document.getElementById('volume-progress');
        const searchInput = document.getElementById('search-input');
        const searchLink = document.getElementById('search-link');
        const searchContainer = document.querySelector('.search-container');
        const profileBtn = document.getElementById('profile-btn');
        const profileDropdown = document.getElementById('profile-dropdown');

        let currentSongIndex = 0;
        let isPlaying = false;
        let isMuted = false;

        // Toggle search bar
        searchLink.addEventListener('click', (e) => {
            e.preventDefault();
            searchContainer.style.display = searchContainer.style.display === 'none' ? 'block' : 'none';
        });

        // Toggle profile dropdown
        profileBtn.addEventListener('click', () => {
            profileDropdown.classList.toggle('show');
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!profileBtn.contains(e.target) && !profileDropdown.contains(e.target)) {
                profileDropdown.classList.remove('show');
            }
        });

        // Search functionality
        searchInput.addEventListener('input', (e) => {
            const searchTerm = e.target.value.toLowerCase();
            const filteredSongs = songs.filter(song => 
                song.name.toLowerCase().includes(searchTerm) || 
                song.artist.toLowerCase().includes(searchTerm)
            );
            
            songsContainer.innerHTML = '';
            createSongCards(filteredSongs);
        });


        

        // Create song cards
        function createSongCards(songsArray = songs) {
            songsContainer.innerHTML = '';
            songsArray.forEach((song, index) => {
                const songCard = document.createElement('div');
                songCard.className = 'song-card';
                songCard.innerHTML = `
                    <img src="${song.image}" alt="${song.name}" onerror="this.src='https://via.placeholder.com/150'">
                    <h3>${song.name}</h3>
                    <p>${song.artist}</p>
                    <div class="play-icon">
                        <i class="fas fa-play"></i>
                    </div>
                `;
                songCard.addEventListener('click', () => playSong(songs.indexOf(song)));
                songsContainer.appendChild(songCard);
            });
        }

        // Play song function
        async function playSong(index) {
            if (index >= 0 && index < songs.length) {
                currentSongIndex = index;
                const song = songs[currentSongIndex];
                
                try {
                    // Set the new source
                    audioPlayer.src = song.src;
                    
                    // Update UI first
                    currentSongImage.src = song.image;
                    currentSongImage.onerror = function() {
                        this.src = 'https://via.placeholder.com/150';
                    };
                    currentSongName.textContent = song.name;
                    currentSongArtist.textContent = song.artist;
                    
                    // Play audio
                    await audioPlayer.play();
                    isPlaying = true;
                    updatePlayButton();
                } catch (error) {
                    console.error("Error playing audio:", error);
                    alert("Could not play the song. Please try again.");
                }
            }
        }

        // Toggle play/pause
        function togglePlay() {
            if (audioPlayer.src) {
                if (isPlaying) {
                    audioPlayer.pause();
                } else {
                    audioPlayer.play().catch(error => {
                        console.error("Error playing audio:", error);
                    });
                }
                isPlaying = !isPlaying;
                updatePlayButton();
            }
        }

        // Update play button icon
        function updatePlayButton() {
            playBtn.innerHTML = isPlaying ? '<i class="fas fa-pause"></i>' : '<i class="fas fa-play"></i>';
        }

        // Format time
        function formatTime(seconds) {
            const minutes = Math.floor(seconds / 60);
            seconds = Math.floor(seconds % 60);
            return `${minutes}:${seconds.toString().padStart(2, '0')}`;
        }

        // Toggle volume mute
        function toggleMute() {
            isMuted = !isMuted;
            audioPlayer.muted = isMuted;
            updateVolumeIcon();
        }

        // Update volume icon
        function updateVolumeIcon() {
            const volumeIcon = volumeBtn.querySelector('i');
            if (isMuted || audioPlayer.volume === 0) {
                volumeIcon.className = 'fas fa-volume-mute';
            } else if (audioPlayer.volume < 0.5) {
                volumeIcon.className = 'fas fa-volume-down';
            } else {
                volumeIcon.className = 'fas fa-volume-up';
            }
        }

        // Handle volume change
        function handleVolumeChange(e) {
            const rect = volumeSlider.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const volume = Math.min(Math.max(x / rect.width, 0), 1);
            audioPlayer.volume = volume;
            volumeProgress.style.width = `${volume * 100}%`;
            isMuted = volume === 0;
            updateVolumeIcon();
        }

        // Event Listeners
        playBtn.addEventListener('click', togglePlay);
        volumeBtn.addEventListener('click', toggleMute);

        volumeSlider.addEventListener('click', handleVolumeChange);
        volumeSlider.addEventListener('mousemove', (e) => {
            if (e.buttons === 1) {
                handleVolumeChange(e);
            }
        });

        audioPlayer.addEventListener('timeupdate', () => {
            const progress = (audioPlayer.currentTime / audioPlayer.duration) * 100;
            progressBar.style.width = `${progress}%`;
            currentTimeSpan.textContent = formatTime(audioPlayer.currentTime);
        });

        audioPlayer.addEventListener('loadedmetadata', () => {
            durationSpan.textContent = formatTime(audioPlayer.duration);
        });

        audioPlayer.addEventListener('ended', () => {
            if (currentSongIndex < songs.length - 1) {
                playSong(currentSongIndex + 1);
            } else {
                playSong(0);
            }
        });

        document.querySelector('.prev-btn').addEventListener('click', () => {
            if (currentSongIndex > 0) {
                playSong(currentSongIndex - 1);
            } else {
                playSong(songs.length - 1);
            }
        });

        document.querySelector('.next-btn').addEventListener('click', () => {
            if (currentSongIndex < songs.length - 1) {
                playSong(currentSongIndex + 1);
            } else {
                playSong(0);    
            }
        });

        document.querySelector('.progress-bar').addEventListener('click', (e) => {
            const progressBar = e.currentTarget;
            const clickPosition = e.offsetX;
            const progressBarWidth = progressBar.offsetWidth;
            const seekTime = (clickPosition / progressBarWidth) * audioPlayer.duration;
            audioPlayer.currentTime = seekTime;
        });

        // Initialize
        createSongCards();
        audioPlayer.volume = 0.5; // Set initial volume
        volumeProgress.style.width = '100%'; // Set initial volume progress
